import React, { useCallback, useEffect, useRef, useState } from 'react';
import { useTheme } from '../theme/ThemeContext';
import { Play, RotateCcw, Gauge } from 'lucide-react';

const API = import.meta.env.VITE_API_URL || '';

// dash.js is large (~600 kB) and is only needed on screens that actually play a
// video, so it is code-split and loaded on demand. Dynamic import also keeps it
// out of the main chunk (Rollup hoisting it together with app code previously
// produced an invalid minified bundle). The module is cached across mounts.
let dashModulePromise = null;
function loadDash() {
  if (!dashModulePromise) dashModulePromise = import('dashjs');
  return dashModulePromise;
}

export function streamUrl(videoId, itag, token) {
  return `${API}/api/yt/media/${videoId}?itag=${itag}&token=${encodeURIComponent(token || '')}`;
}

export function downloadUrl(videoId, itag, token) {
  return `${API}/api/yt/media/${videoId}?itag=${itag}&download=1&token=${encodeURIComponent(token || '')}`;
}

// The MPD is generated by the backend from the innertube adaptive formats; its
// BaseURLs point back at /api/yt/media (the same-egress byte proxy). The token
// travels in the query string so a bare <video>/dash.js fetch is authenticated.
export function dashUrl(videoId, token) {
  return `${API}/api/yt/dash/${videoId}?token=${encodeURIComponent(token || '')}`;
}

// Hands the file to the browser's own downloader. The proxy sets
// `Content-Disposition: attachment`, so the browser saves it instead of
// navigating. A synthetic (non-user-gesture) click may be ignored by some
// browsers, but every call site here is a real button press.
export function triggerDownload(videoId, token, itag = 'best') {
  const a = document.createElement('a');
  a.href = downloadUrl(videoId, itag, token);
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
}

function fmtBytes(n) {
  if (!n) return '';
  const mb = n / (1024 * 1024);
  return mb >= 1024 ? `${(mb / 1024).toFixed(2)} GB` : `${(mb / 8).toFixed(1)} MBps`;
}

export default function YoutubePlayer({
  videoId,
  token,
  poster,
  autoPlay = true,
  controls = true,
  onEnded,
  onError,
  style,
  fill = false,
}) {
  const { theme } = useTheme();
  const videoRef = useRef(null);
  const dashRef = useRef(null);
  const onEndedRef = useRef(onEnded);
  const onErrorRef = useRef(onError);
  onEndedRef.current = onEnded;
  onErrorRef.current = onError;

  const [state, setState] = useState('loading');
  const [errMsg, setErrMsg] = useState('');
  const [muted, setMuted] = useState(autoPlay);
  const [fallback, setFallback] = useState(false);
  const [progItag, setProgItag] = useState(18);
  const [levels, setLevels] = useState([]);
  const [level, setLevel] = useState(-1);
  const [menuOpen, setMenuOpen] = useState(false);
  const [nonce, setNonce] = useState(0);

  useEffect(() => {
    const video = videoRef.current;
    if (!video || !videoId) return;
    let cancelled = false;
    let player = null;
    let triedFallback = false;

    setState('loading');
    setErrMsg('');
    setLevels([]);
    setLevel(-1);
    setFallback(false);
    setMenuOpen(false);
    video.muted = autoPlay;

    const destroy = () => {
      if (player) {
        try { player.reset(); } catch (e) {}
        player = null;
        dashRef.current = null;
      }
    };

    const fail = (msg) => {
      if (cancelled) return;
      const raw = String(msg || '');
      // Surface a friendly message for YouTube's anti-bot notice; the concrete
      // per-client reason is logged server-side for the operator.
      const shown = /bot|sign in|login|verify/i.test(raw)
        ? 'Playback is temporarily unavailable. Tap Retry.'
        : (raw || 'Playback failed');
      setState('error');
      setErrMsg(shown);
      onErrorRef.current && onErrorRef.current(new Error(shown));
    };

    // Progressive muxed (360p) path: last-resort fallback when DASH cannot start
    // (e.g. no MediaSource, or the MPD/segment proxy fails). Uses the same byte
    // proxy via the /api/yt/streams metadata.
    const setupProgressive = async () => {
      destroy();
      try {
        const res = await fetch(`${API}/api/yt/streams/${videoId}`, {
          headers: { Authorization: `Bearer ${token || ''}` },
        });
        const data = await res.json().catch(() => ({}));
        if (cancelled) return;
        const prog = (data.formats || [])
          .filter((f) => f.hasVideo && f.hasAudio)
          .sort((a, b) => (b.height || 0) - (a.height || 0));
        if (!prog.length) { fail(data.reason || data.error || 'No playable stream'); return; }
        setProgItag(prog[0].itag);
        setFallback(true);
        setState('ready');
      } catch (e) {
        if (!cancelled) fail(e.message);
      }
    };

    const setupDash = async () => {
      if (typeof window === 'undefined' || !window.MediaSource) { setupProgressive(); return; }
      let MediaPlayer;
      try {
        ({ MediaPlayer } = await loadDash());
      } catch (e) {
        setupProgressive();
        return;
      }
      if (cancelled) return;
      try {
        player = MediaPlayer().create();
        dashRef.current = player;
        player.updateSettings({
          streaming: {
            buffer: {
              fastSwitchEnabled: true,
              bufferToKeep: 24,
              bufferTimeDefault: 24,
              bufferTimeAtTopQuality: 30,
              bufferTimeAtTopQualityLongForm: 60,
              initialBufferLevel: 8,
              longFormContentDurationThreshold: 300,
            },
            abr: {
              autoSwitchBitrate: { video: true, audio: true },
              // Start around 720p instead of dash.js's ~480p default; ABR still
              // drops/raises based on measured throughput.
              initialBitrate: { video: 1500, audio: 128 },
              // Googlevideo is reached through our byte proxy, so connection
              // setup latency is not a bandwidth signal. Ignoring it lets ABR
              // ramp up to the video's real quality instead of pinning to 360p.
              throughput: { useDeadTimeLatency: false },
            },
            cmcd: { enabled: false },
          },
        });
        player.on('streamInitialized', () => {
          if (cancelled) return;
          try {
            const reps = player.getRepresentationsByType('video') || [];
            setLevels(
              reps
                .map((r, i) => ({ index: i, height: r.height || 0, width: r.width || 0, bitrate: r.bandwidth || 0 }))
                .filter((r) => r.height > 0)
                .sort((a, b) => b.height - a.height)
            );
          } catch (e) { setLevels([]); }
          setState('ready');
          if (autoPlay) video.play().catch(() => {});
        });
        const onErr = () => {
          if (cancelled) return;
          if (!triedFallback) { triedFallback = true; setupProgressive(); }
          else fail('Playback failed');
        };
        player.on('error', onErr);
        player.on('playbackError', onErr);
        player.on('playbackEnded', () => { onEndedRef.current && onEndedRef.current(); });
        player.initialize(video, dashUrl(videoId, token), autoPlay);
      } catch (e) {
        setupProgressive();
      }
    };

    setupDash();

    return () => {
      cancelled = true;
      destroy();
    };
  }, [videoId, token, nonce, autoPlay]);

  // Autoplay policies block unmuted playback, so the element starts muted and we
  // try to restore sound on the first canplay. If the browser still refuses, it
  // stays muted (matching the tap-to-unmute behaviour of the app).
  const handleCanPlay = useCallback(() => {
    const v = videoRef.current;
    if (!v) return;
    if (!autoPlay) { v.muted = false; setMuted(false); return; }
    v.muted = false;
    v.play().then(() => setMuted(false)).catch(() => {
      v.muted = true;
      setMuted(true);
      v.play().catch(() => {});
    });
  }, [autoPlay]);

  const chooseLevel = (lvl) => {
    setLevel(lvl);
    setMenuOpen(false);
    const player = dashRef.current;
    if (!player) return;
    try {
      if (lvl < 0) {
        player.updateSettings({ streaming: { abr: { autoSwitchBitrate: { video: true, audio: true } } } });
      } else {
        player.updateSettings({ streaming: { abr: { autoSwitchBitrate: { video: false, audio: true } } } });
        player.setRepresentationForTypeByIndex('video', lvl);
      }
    } catch (e) {}
  };

  const src = state === 'ready' && fallback ? `${streamUrl(videoId, progItag, token)}&_=${nonce}` : undefined;

  return (
    <div
      style={{ position: 'relative', width: '100%', height: fill ? '100%' : undefined, aspectRatio: fill ? undefined : '16/9', background: '#000', overflow: 'hidden', ...style }}
      onMouseLeave={() => setMenuOpen(false)}
    >
      <video
        ref={videoRef}
        src={src}
        poster={poster}
        controls={controls}
        autoPlay={autoPlay}
        muted={muted}
        playsInline
        preload="metadata"
        onCanPlay={handleCanPlay}
        onEnded={fallback ? () => { onEndedRef.current && onEndedRef.current(); } : undefined}
        onError={fallback ? () => { setState('error'); setErrMsg('Playback failed'); } : undefined}
        style={{ width: '100%', height: '100%', objectFit: fill ? 'contain' : 'cover', background: '#000' }}
      />
      {state === 'loading' && (
        <div style={{ position: 'absolute', inset: 0, display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
          <div className="spinner" style={{ width: 40, height: 40, border: '3px solid rgba(255,255,255,0.25)', borderTopColor: theme.primary, borderRadius: '50%' }} />
        </div>
      )}
      {state === 'error' && (
        <div style={{ position: 'absolute', inset: 0, display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', color: '#eee', textAlign: 'center', padding: 24, gap: 12 }}>
          <Play size={30} color={theme.primary} />
          <div style={{ fontSize: 13, opacity: 0.85 }}>{errMsg}</div>
          <button onClick={() => setNonce((n) => n + 1)} style={{ display: 'flex', alignItems: 'center', gap: 6, background: theme.primary, color: '#fff', border: 'none', borderRadius: 20, padding: '8px 16px', fontWeight: 700, cursor: 'pointer', fontSize: 13 }}>
            <RotateCcw size={14} /> Retry
          </button>
        </div>
      )}
      {state === 'ready' && levels.length > 1 && (
        <div style={{ position: 'absolute', top: 10, right: 10, zIndex: 3 }}>
          <button
            onClick={() => setMenuOpen((o) => !o)}
            title="Quality"
            style={{ display: 'flex', alignItems: 'center', gap: 5, border: 'none', cursor: 'pointer', borderRadius: 14, padding: '5px 10px', fontSize: 11, fontWeight: 700, background: 'rgba(20,14,32,0.82)', color: '#fff' }}
          >
            <Gauge size={13} />
            {level < 0 ? 'Auto' : `${levels.find((l) => l.index === level)?.height || ''}p`}
          </button>
          {menuOpen && (
            <div style={{ position: 'absolute', top: 32, right: 0, minWidth: 110, background: 'rgba(20,14,32,0.96)', borderRadius: 10, overflow: 'hidden', boxShadow: '0 8px 28px rgba(0,0,0,0.5)' }}>
              <button onClick={() => chooseLevel(-1)} style={{ display: 'block', width: '100%', textAlign: 'left', border: 'none', cursor: 'pointer', padding: '8px 12px', fontSize: 12, fontWeight: level < 0 ? 800 : 500, background: level < 0 ? theme.primary : 'transparent', color: '#fff' }}>
                Auto
              </button>
              {levels.map((l) => (
                <button
                  key={l.index}
                  onClick={() => chooseLevel(l.index)}
                  title={fmtBytes(l.bitrate * 8)}
                  style={{ display: 'block', width: '100%', textAlign: 'left', border: 'none', cursor: 'pointer', padding: '8px 12px', fontSize: 12, fontWeight: level === l.index ? 800 : 500, background: level === l.index ? theme.primary : 'transparent', color: '#fff' }}
                >
                  {l.height}p{l.height >= 720 ? ' HD' : ''}
                </button>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
